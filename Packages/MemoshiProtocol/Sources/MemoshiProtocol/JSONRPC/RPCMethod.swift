/// A method of the typed API (protocol.md §5). Each method is a caseless enum that names its
/// wire method and its parameter and result types, for example ``ChatsSend``.
///
/// The same descriptor serves both carriers (D78): the iPhone and iPad app passes it to its
/// in-process engine through ``MemoshiAPI``, and the Mac encodes it as JSON-RPC with
/// ``JSONRPCCodec``.
public protocol RPCMethod: Sendable {
  /// The parameters.
  associatedtype Params: Codable & Hashable & Sendable
  /// The result.
  associatedtype Result: Codable & Hashable & Sendable

  /// The wire method name, `<namespace>.<verb>`, such as `chats.send`.
  static var name: String { get }

  /// Whether the method changes state. A mutating method takes a client-generated `requestId`
  /// and is applied at most once per ID (protocol.md §9); its parameters conform to
  /// ``IdempotentParams``.
  static var isMutating: Bool { get }
}

/// Parameters of a mutating method: they carry the client's idempotency key.
public protocol IdempotentParams {
  /// A ULID generated by the client and reused after a reconnect or restart.
  var requestId: ULID { get }
}

/// Every method this build models, in catalog order.
public enum MethodRegistry {
  /// The registered methods.
  public static let methods: [any RPCMethod.Type] = [
    SystemHello.self,
    SystemPing.self,
    SystemStatus.self,
    EventsSubscribe.self,
    EventsFocus.self,
    EventsUnsubscribe.self,
    BotsList.self,
    BotsGet.self,
    BotsCreate.self,
    BotsUpdate.self,
    BotsGrantsList.self,
    BotsGrantsUpdate.self,
    BotsGrantsRevoke.self,
    ChatsList.self,
    ChatsHistory.self,
    ChatsSend.self,
    ChatsAbort.self,
    SessionsCreate.self,
    SessionsDelete.self,
    TrashList.self,
    TrashRestore.self,
    TrashEmpty.self,
    ModelsProvidersList.self,
    ModelsProvidersConfigure.self,
    ModelsList.self,
    TasksGet.self,
    TasksAbort.self,
    TasksGraph.self,
    TasksHistory.self,
    CardsList.self,
    CardsGet.self,
    CardsRespond.self,
    ApprovalsList.self,
    HostKeychainGet.self,
  ]

  /// The method with this wire name.
  public static func method(named name: String) -> (any RPCMethod.Type)? {
    methods.first { $0.name == name }
  }
}
