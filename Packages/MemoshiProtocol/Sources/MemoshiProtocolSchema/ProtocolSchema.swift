import MemoshiProtocol

/// The protocol's JSON Schema (Draft 2020-12), derived from the Swift types in
/// `MemoshiProtocol` (D78). Nothing here is a hand-written per-type schema: each struct's schema
/// is learned by running its `init(from:)` against a recording decoder, leaf types describe
/// themselves through ``WireShaped``, and the discriminated unions are built from the method,
/// event and device message registries.
///
/// `scripts/protocol-schema.sh` writes ``canonicalText()`` to `protocol/protocol.schema.json`.
public enum ProtocolSchema {
  /// The JSON Schema dialect.
  public static let dialect = "https://json-schema.org/draft/2020-12/schema"

  /// The schema document.
  public static func document() throws -> JSONValue {
    let generator = SchemaGenerator()
    try generator.defineEverything()
    return [
      "$schema": .string(dialect),
      "$comment": .string(
        "Generated by memoshi-protocol-schema from the Swift types in Packages/MemoshiProtocol. "
          + "Do not edit; regenerate with scripts/protocol-schema.sh."),
      "title": "Memoshi protocol",
      "description": .string(
        "Wire shapes of the Memoshi protocol, major version \(ProtocolVersion.current): JSON-RPC "
          + "frames for each method (<Method>Request, <Method>Response), the event envelope by "
          + "type (<Type>Event), device messages by type (<Type>Message) and errors (RPCError)."
      ),
      "$defs": .object(generator.definitions),
    ]
  }

  /// The schema document as canonical JSON text, byte-identical across runs.
  public static func canonicalText() throws -> String {
    try document().canonicalText
  }

  /// The `$defs` name of an event type's envelope, such as `MessageCreatedEvent` for
  /// `message.created`.
  public static func eventDefinitionName(for type: String) -> String {
    pascalCase(type) + "Event"
  }

  /// The `$defs` name of a device message type's envelope, such as `LeaseClaimMessage` for
  /// `lease.claim`.
  public static func deviceMessageDefinitionName(for type: String) -> String {
    pascalCase(type) + "Message"
  }

  /// `message.created` → `MessageCreated`, `lease.handOver` → `LeaseHandOver`.
  public static func pascalCase(_ dottedName: String) -> String {
    dottedName.split { $0 == "." || $0 == "_" }
      .map { $0.prefix(1).uppercased() + $0.dropFirst() }
      .joined()
  }
}

/// A Swift type the generator cannot describe.
public struct SchemaGenerationError: Error, CustomStringConvertible {
  /// What went wrong.
  public let description: String
}
