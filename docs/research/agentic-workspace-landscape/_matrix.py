#!/usr/bin/env python3
"""Regenerate matrix.md from the "Matrix row" YAML block of every projects/*.md profile.

Stdlib only. Run from anywhere:  python3 docs/research/agentic-workspace-landscape/_matrix.py
"""

from __future__ import annotations

import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent
PROJECTS = ROOT / "projects"
OUT = ROOT / "matrix.md"
TEMPLATE = ROOT / "_template.md"

KEY_LINE = re.compile(r"^([a-z0-9_]+):[ \t]*(.*)$")
INLINE_COMMENT = re.compile(r"\s+#\s(.*)$")

TABLES: list[tuple[str, list[str]]] = [
    ("Identity and traction", ["category", "maker", "license", "stars", "latest_release", "platforms", "pricing", "maturity"]),
    ("Engine and runtime", ["agent_engine", "engines_supported", "model_access", "execution_env", "per_bot_computer", "stack"]),
    ("Assistant capabilities", ["persistent_bots", "memory", "routines", "group_chat", "connectors", "channels", "mobile", "voice"]),
    ("Workspace, trust, and deployment", ["coding_workspace", "browser_use", "computer_use", "approvals", "e2e_encryption", "self_host", "multi_user"]),
]

CATEGORY_ORDER = [
    "closed-hosted-agents",
    "oss-bot-roster-desktop",
    "oss-self-hosted-platform",
    "personal-assistant-gateway",
    "agent-workspace-ide",
    "coding-harness",
    "other",
]


def matrix_block(text: str) -> str | None:
    section = text.split("## Matrix row", 1)
    if len(section) < 2:
        return None
    match = re.search(r"```ya?ml\n(.*?)```", section[1], re.S)
    return match.group(1) if match else None


def split_comment(value: str) -> tuple[str, str]:
    match = INLINE_COMMENT.search(value)
    if not match:
        return value.strip(), ""
    return value[: match.start()].strip(), match.group(1).strip()


def template_comments() -> set[str]:
    """Inline comments that come from _template.md itself, so copies of them are dropped as boilerplate."""
    block = matrix_block(TEMPLATE.read_text(encoding="utf-8")) or ""
    return {split_comment(match.group(2))[1] for raw in block.splitlines() if (match := KEY_LINE.match(raw))} - {""}


def parse_row(block: str, boilerplate: set[str]) -> dict[str, str]:
    row: dict[str, str] = {}
    for raw in block.splitlines():
        match = KEY_LINE.match(raw)
        if not match:
            continue
        key = match.group(1)
        value, comment = split_comment(match.group(2))
        if len(value) >= 2 and value[0] == value[-1] and value[0] in "\"'":
            value = value[1:-1]
        if value.startswith("[") and value.endswith("]"):
            value = ", ".join(part.strip().strip("\"'") for part in value[1:-1].split(",") if part.strip())
        if comment and comment not in boilerplate and key != "category":
            value = f"{value} ({comment})" if value else comment
        row[key] = value
    return row


def cell(value: str) -> str:
    return (value or "").replace("|", "\\|").replace("\n", " ") or "-"


def category_rank(row: dict[str, str]) -> tuple[int, str]:
    category = row.get("category", "other")
    rank = CATEGORY_ORDER.index(category) if category in CATEGORY_ORDER else len(CATEGORY_ORDER)
    return rank, row.get("name", "").lower()


def main() -> None:
    boilerplate = template_comments()
    rows: list[dict[str, str]] = []
    skipped: list[str] = []
    for path in sorted(PROJECTS.glob("*.md")):
        block = matrix_block(path.read_text(encoding="utf-8"))
        if block is None:
            skipped.append(path.name)
            continue
        row = parse_row(block, boilerplate)
        row["_file"] = f"projects/{path.name}"
        row.setdefault("name", path.stem)
        rows.append(row)
    rows.sort(key=category_rank)

    lines = [
        "# Comparison matrix (generated)",
        "",
        "Generated by `_matrix.py` from the `Matrix row` block of each profile in `projects/`. "
        "Do not edit by hand: fix the profile and rerun `python3 docs/research/agentic-workspace-landscape/_matrix.py`.",
        "",
        f"{len(rows)} profiles.",
    ]
    if skipped:
        lines.append(f"Profiles without a Matrix row block: {', '.join(skipped)}.")
    for title, keys in TABLES:
        lines += ["", f"## {title}", "", "| Product | " + " | ".join(keys) + " |", "|" + "---|" * (len(keys) + 1)]
        for row in rows:
            name = f"[{cell(row['name'])}]({row['_file']})"
            lines.append("| " + " | ".join([name] + [cell(row.get(key, "")) for key in keys]) + " |")
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {OUT.name} with {len(rows)} rows")


if __name__ == "__main__":
    main()
